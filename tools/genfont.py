def pattern_bits(row):
    v = 0
    for i, ch in enumerate(row):
        if ch == '#':
            v |= 1 << (4 - i)
    return v

def normal_tile(rows):
    out = []
    for r in range(8):
        p = ((pattern_bits(rows[r]) if r < len(rows) else 0) << 2)
        out += [p, 0x00]
    return out

def inverse_tile(rows):
    out = []
    for r in range(8):
        p = (((pattern_bits(rows[r]) if r < len(rows) else 0) << 2) ^ 0xFF)
        out += [p, 0x00]
    return out

